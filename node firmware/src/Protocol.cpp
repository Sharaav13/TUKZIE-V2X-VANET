// Creates the data payload in a CSV format
size_t createFrame(const Frame &f, char *out, size_t cap) {
  return snprintf(out, cap, "%u,%c,%u,%u,%.6f,%.6f,%.1f,%.1f",
                  f.ver, f.type, f.node, f.seq,
                  f.lat, f.lon, f.speed, f.heading);
}
